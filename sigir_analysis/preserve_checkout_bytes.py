"""Record explicit Git checkout line endings for checksum-backed research inputs.

Scientific files are not modified. Git stores normalized text but must restore
the original checksum-verified bytes on Windows and POSIX checkouts alike.
"""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'sigir_analysis'


def main():
    read=lambda name:json.loads((OUT/name).read_text(encoding='utf-8'))
    paths=set(read('analysis_protocol.json')['input_hashes'])
    paths.update(read('recovered_ranking_validation.json')['source_hashes'])
    paths.update('sigir_analysis/'+n for n in read('preserved_analysis_hashes.json'))
    paths.update('sigir_analysis/'+n for n in read('density_promotion_validation.json')['promoted_hashes'])
    paths.add('sigir_analysis/trec_judgment_density_frontier.csv')
    paths.add('sigir_analysis/statistical_tests.csv')
    review=json.loads((ROOT/'reports/50_CASE_FAILURE_REVIEW_STATUS.json').read_text())
    paths.update(review[k] for k in ['source_worksheet','checkpoint','human_decision_log'])
    for audit in ['ranking_recovery_final_audit.json','trec_retrieval_state_final_audit.json']:
        record=read(audit)
        paths.update('sigir_analysis/'+n for n in record.get('evidence_hashes',record.get('hashes',{})))
    lines=['# Preserve original checksum-backed research bytes across platform checkouts.',
           '# Generated by sigir_analysis/preserve_checkout_bytes.py; scientific files unchanged.']
    policies={}
    for name in sorted(paths):
        if '/cache/' in name or name.startswith('local_data/'):continue
        raw=(ROOT/name).read_bytes()
        if b'\x00' in raw or raw.count(b'\n')!=raw.count(b'\r\n') and b'\r\n' in raw:
            policy='-text'
        elif b'\r\n' in raw:policy='text eol=crlf'
        else:policy='text eol=lf'
        lines.append('/'+name+' '+policy);policies[name]=policy
    path=ROOT/'.gitattributes'
    if path.exists() and not path.read_text().startswith('# Preserve original checksum-backed research bytes'):
        raise ValueError('Existing unrelated .gitattributes requires a reviewed merge, not replacement.')
    path.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    (OUT/'checkout_byte_integrity.json').write_text(json.dumps(dict(
        purpose='Explicit checkout conversion preserves original raw SHA256s without regenerating scientific files.',
        scientific_files_modified=False,policies=policies),indent=2)+'\n',encoding='utf-8')
    print(f'Explicit checkout byte policies recorded for {len(policies)} research files; scientific bytes unchanged.')


if __name__=='__main__':main()
